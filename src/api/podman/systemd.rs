//! podman's `generate systemd` (`GET /libpod/generate/{name}/systemd`):
//! the units that start and stop an existing container, or a pod and its
//! containers, with velarx.  podman deprecates it for Quadlet; the units
//! are those of podman without `--new` (refused: it needs the command line
//! the container was made with): `Type=forking`, `ExecStart=velarx
//! start`, `PIDFile=` the monitor's.  In a unit `velarx start` runs the
//! container in the unit: its monitor is the unit's main process.

use super::error::{ApiError, ApiResult, Kind};
use super::lifecycle;
use crate::api::AppState;
use std::collections::BTreeMap;
use velarx_db::ContainerRecord;

/// podman's policies (pkg/systemd/define).
const RESTART_POLICIES: &[&str] = &[
    "no",
    "on-success",
    "on-failure",
    "on-abnormal",
    "on-watchdog",
    "on-abort",
    "always",
];

/// podman waits this long more than the stop timeout before systemd kills.
const MIN_TIMEOUT_STOP_SEC: u32 = 60;

#[derive(Debug, Clone)]
pub(crate) struct Options {
    pub use_name: bool,
    pub no_header: bool,
    pub restart_policy: String,
    pub restart_sec: u32,
    pub start_timeout: u32,
    pub stop_timeout: u32,
    pub container_prefix: String,
    pub pod_prefix: String,
    pub separator: String,
    pub wants: Vec<String>,
    pub after: Vec<String>,
    pub requires: Vec<String>,
    pub env: Vec<String>,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            use_name: false,
            no_header: false,
            restart_policy: "on-failure".into(),
            restart_sec: 0,
            start_timeout: 0,
            stop_timeout: 10,
            container_prefix: "container".into(),
            pod_prefix: "pod".into(),
            separator: "-".into(),
            wants: Vec::new(),
            after: Vec::new(),
            requires: Vec::new(),
            env: Vec::new(),
        }
    }
}

/// What the units run: this engine, with its configuration.
fn executable(state: &AppState) -> String {
    match state.container_service.engine_command() {
        Some(cmd) => cmd
            .iter()
            .map(|a| escape_arg(&a.to_string_lossy()))
            .collect::<Vec<_>>()
            .join(" "),
        None => "/usr/bin/velarx".to_string(),
    }
}

/// One word of an `ExecStart=` line (systemd.service(5), "Command lines"):
/// `$` is doubled, as it starts a variable there, and a lone `;`, which
/// ends a command, is `\;`; the rest as [`escape_word`].
pub(crate) fn escape_arg(arg: &str) -> String {
    if arg == ";" {
        return "\\;".to_string();
    }
    escape_word(&arg.replace('$', "$$"))
}

/// One word of an `Environment=` line, where `$` is not special, or of a
/// command line (systemd.syntax(7), "Quoting"): `%` is doubled, a backslash
/// is escaped, and a word that is empty or has a blank, a quote or a control
/// character is quoted with the C escapes systemd reads, so a newline stays
/// on its line.
fn escape_word(word: &str) -> String {
    let mut out = String::with_capacity(word.len());
    for c in word.chars() {
        match c {
            '%' => out.push_str("%%"),
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c.is_ascii_control() => out.push_str(&format!("\\x{:02x}", c as u8)),
            c => out.push(c),
        }
    }
    let quote = word.is_empty()
        || word
            .chars()
            .any(|c| c.is_ascii_whitespace() || c.is_ascii_control() || matches!(c, '"' | '\''));
    if quote {
        format!("\"{out}\"")
    } else {
        out
    }
}

/// podman's `formatOptions`: an option starts a continued line.
fn format_options(words: &[String]) -> String {
    let mut out = String::new();
    for (i, w) in words.iter().enumerate() {
        if i > 0 {
            out.push_str(if w.starts_with('-') { " \\\n\t" } else { " " });
        }
        out.push_str(w);
    }
    out
}

fn service_name(prefix: &str, sep: &str, name: &str) -> String {
    if prefix.is_empty() {
        name.to_string()
    } else {
        format!("{prefix}{sep}{name}")
    }
}

/// A unit to write.
pub(crate) struct Unit<'a> {
    pub service: String,
    /// `velarx start` of a container, `velarx pod start` of a pod
    pub start: Vec<String>,
    pub stop: Vec<String>,
    pub pid_file: String,
    pub run_root: String,
    /// The unit of the pod of a container
    pub bound_to: Vec<String>,
    /// The units of the containers of a pod
    pub required: Vec<String>,
    pub opts: &'a Options,
    pub version: &'a str,
    pub timestamp: &'a str,
}

impl Unit<'_> {
    pub fn render(&self) -> String {
        let o = self.opts;
        let mut s = format!("# {}.service\n", self.service);
        if !o.no_header {
            s += &format!("# autogenerated by velarx {}\n", self.version);
            s += &format!("# {}\n", self.timestamp);
        }
        s += &format!(
            "\n[Unit]\nDescription=Podman {}.service\nDocumentation=man:podman-generate-systemd(1)\n\
             Wants=network-online.target\nAfter=network-online.target\nRequiresMountsFor={}\n",
            self.service, self.run_root
        );
        let units = |v: &[String]| {
            v.iter()
                .map(|u| format!("{u}.service"))
                .collect::<Vec<_>>()
                .join(" ")
        };
        if !self.bound_to.is_empty() {
            s += &format!(
                "BindsTo={}\nAfter={}\n",
                units(&self.bound_to),
                units(&self.bound_to)
            );
        }
        if !self.required.is_empty() {
            s += &format!(
                "Wants={}\nBefore={}\n",
                units(&self.required),
                units(&self.required)
            );
        }
        if !(o.wants.is_empty() && o.after.is_empty() && o.requires.is_empty()) {
            s += "\n# User-defined dependencies\n";
        }
        for (key, v) in [
            ("Wants", &o.wants),
            ("After", &o.after),
            ("Requires", &o.requires),
        ] {
            if !v.is_empty() {
                s += &format!("{key}={}\n", v.join(" "));
            }
        }
        s += "\n[Service]\nEnvironment=PODMAN_SYSTEMD_UNIT=%n\n";
        for e in &o.env {
            s += &format!("Environment={}\n", escape_word(e));
        }
        s += &format!("Restart={}\n", o.restart_policy);
        if o.restart_sec > 0 {
            s += &format!("RestartSec={}\n", o.restart_sec);
        }
        if o.start_timeout != 0 {
            s += &format!("TimeoutStartSec={}\n", o.start_timeout);
        }
        s += &format!(
            "TimeoutStopSec={}\n",
            o.stop_timeout.saturating_add(MIN_TIMEOUT_STOP_SEC)
        );
        s += &format!("ExecStart={}\n", format_options(&self.start));
        s += &format!("ExecStop={}\n", format_options(&self.stop));
        s += &format!("ExecStopPost={}\n", format_options(&self.stop));
        s += &format!(
            "PIDFile={}\nType=forking\n\n[Install]\nWantedBy=default.target\n",
            self.pid_file
        );
        s
    }
}

/// The pid file of the monitor of a container: its `--conmon-pidfile`, or
/// the one in its monitor's directory.
fn pid_file(state: &AppState, rec: &ContainerRecord) -> ApiResult<String> {
    let cfg = lifecycle::config_of(rec)?;
    Ok(match cfg.conmon_pid_file.filter(|p| !p.is_empty()) {
        Some(p) => p,
        None => state
            .container_service
            .mon_dir(&rec.id)
            .join(velarx_core::services::MONITOR_PID_FILE)
            .display()
            .to_string(),
    })
}

/// The digests the container was made from (its image, the images mounted in
/// it) where its digests are enforced: the unit's start gives them, so that
/// its command line, not the record, is what the images are held to.
fn verified_digests(state: &AppState, rec: &ContainerRecord) -> ApiResult<Vec<String>> {
    let cfg = lifecycle::config_of(rec)?;
    if state.container_service.digests_enforced(&cfg).is_none() {
        return Ok(Vec::new());
    }
    let mut digests: Vec<String> = Vec::new();
    let made = cfg.pinned.iter().map(|p| p.digest.to_string()).chain(
        cfg.mounts
            .iter()
            .filter_map(|m| m.image.as_ref()?.digest.clone()),
    );
    for d in made {
        if !digests.contains(&d) {
            digests.push(d);
        }
    }
    Ok(digests)
}

fn exe_words(exe: &str, rest: &[&str]) -> Vec<String> {
    let mut v: Vec<String> = exe.split(' ').map(str::to_string).collect();
    v.extend(rest.iter().map(|s| s.to_string()));
    v
}

fn container_unit<'a>(
    state: &AppState,
    rec: &ContainerRecord,
    o: &'a Options,
    exe: &str,
    stamp: &'a str,
    bound_to: Vec<String>,
) -> ApiResult<(String, Unit<'a>)> {
    let name = rec.name.clone().unwrap_or_default();
    let target = if o.use_name && !name.is_empty() {
        name
    } else {
        rec.id.clone()
    };
    let service = service_name(&o.container_prefix, &o.separator, &target);
    let t = o.stop_timeout.to_string();
    let mut start = vec!["start".to_string()];
    for digest in verified_digests(state, rec)? {
        start.extend(["--verify-image".to_string(), digest]);
    }
    start.push(target.clone());
    let start: Vec<&str> = start.iter().map(String::as_str).collect();
    let unit = Unit {
        service: service.clone(),
        start: exe_words(exe, &start),
        stop: exe_words(exe, &["stop", "-t", &t, &target]),
        pid_file: pid_file(state, rec)?,
        run_root: state.config.server.state_dir.display().to_string(),
        bound_to,
        required: Vec::new(),
        opts: o,
        version: env!("CARGO_PKG_VERSION"),
        timestamp: stamp,
    };
    Ok((service, unit))
}

/// The options of the units, as the query of a client says them (none:
/// the default).
#[derive(Default)]
pub(crate) struct Asked {
    pub use_name: bool,
    pub no_header: bool,
    pub restart_policy: Option<String>,
    pub restart_sec: Option<u32>,
    pub start_timeout: Option<u32>,
    pub stop_timeout: Option<u32>,
    pub container_prefix: Option<String>,
    pub pod_prefix: Option<String>,
    pub separator: Option<String>,
    pub wants: Vec<String>,
    pub after: Vec<String>,
    pub requires: Vec<String>,
    pub env: Vec<String>,
}

/// The options of the units of `asked`, checked.
pub(crate) fn options_of(asked: Asked) -> ApiResult<Options> {
    let mut o = Options {
        use_name: asked.use_name,
        no_header: asked.no_header,
        ..Default::default()
    };
    if let Some(p) = asked.restart_policy {
        if !RESTART_POLICIES.contains(&p.as_str()) {
            return Err(ApiError::bad_request(format!(
                "{p} is not a valid restart policy"
            )));
        }
        o.restart_policy = p;
    }
    o.restart_sec = asked.restart_sec.unwrap_or(0);
    o.start_timeout = asked.start_timeout.unwrap_or(0);
    o.stop_timeout = asked.stop_timeout.unwrap_or(o.stop_timeout);
    if let Some(v) = asked.container_prefix {
        o.container_prefix = v;
    }
    if let Some(v) = asked.pod_prefix {
        o.pod_prefix = v;
    }
    if let Some(v) = asked.separator {
        o.separator = v;
    }
    o.wants = asked.wants;
    o.after = asked.after;
    o.requires = asked.requires;
    o.env = asked.env;
    Ok(o)
}

/// The units of the container or pod `name`: by the name of each.
pub(crate) async fn generate_of(
    state: &AppState,
    name: &str,
    o: &Options,
) -> ApiResult<BTreeMap<String, String>> {
    let o = o.clone();
    let exe = executable(state);
    let stamp = chrono::Local::now().format("%a %b %e %T %Z %Y").to_string();
    let mut units = BTreeMap::new();
    if let Some(rec) = ApiError::found(lifecycle::resolve(state, name).await)? {
        if let Some(p) = super::pods::pod_of_container(state, &rec.id).await {
            if p.2 {
                return Err(ApiError::bad_request(format!(
                    "{} is the infra container of the pod {}: generate the units of the pod",
                    rec.id, p.1
                )));
            }
        }
        let (service, unit) = container_unit(state, &rec, &o, &exe, &stamp, Vec::new())?;
        units.insert(service, unit.render());
        return Ok(units);
    }
    let pod = ApiError::found(state.pod_service.get(name).await)?.ok_or_else(|| {
        ApiError::no_such(Kind::Container, format!("{name}: no such container or pod"))
    })?;
    let infra_id = pod.infra_container_id.clone().ok_or_else(|| {
        ApiError::bad_request(format!(
            "the pod {} has no infra container: its units need one to wait for",
            pod.name
        ))
    })?;
    let infra = lifecycle::resolve(state, &infra_id).await?;
    let target = if o.use_name {
        pod.name.clone()
    } else {
        pod.id.clone()
    };
    let pod_service = service_name(&o.pod_prefix, &o.separator, &target);
    let mut required = Vec::new();
    let mut ctr_units = Vec::new();
    // (the pod's start gives the digests of its containers, as their units do)
    let mut pod_start = vec!["pod".to_string(), "start".to_string()];
    for id in &pod.container_ids {
        let rec = lifecycle::resolve(state, id).await?;
        for digest in verified_digests(state, &rec)? {
            if !pod_start.contains(&digest) {
                pod_start.extend(["--verify-image".to_string(), digest]);
            }
        }
        let (service, unit) =
            container_unit(state, &rec, &o, &exe, &stamp, vec![pod_service.clone()])?;
        required.push(service.clone());
        ctr_units.push((service, unit.render()));
    }
    required.sort();
    let t = o.stop_timeout.to_string();
    let pod_unit = Unit {
        service: pod_service.clone(),
        start: {
            pod_start.push(target.clone());
            let words: Vec<&str> = pod_start.iter().map(String::as_str).collect();
            exe_words(&exe, &words)
        },
        stop: exe_words(&exe, &["pod", "stop", "-t", &t, &target]),
        pid_file: pid_file(state, &infra)?,
        run_root: state.config.server.state_dir.display().to_string(),
        bound_to: Vec::new(),
        required,
        opts: &o,
        version: env!("CARGO_PKG_VERSION"),
        timestamp: &stamp,
    };
    units.insert(pod_service, pod_unit.render());
    units.extend(ctr_units);
    Ok(units)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_unit_is_podmans() {
        let o = Options {
            wants: vec!["a.service".into()],
            env: vec!["FOO=a b".into()],
            restart_sec: 5,
            ..Default::default()
        };
        let u = Unit {
            service: "container-web".into(),
            start: vec!["/usr/bin/velarx".into(), "start".into(), "web".into()],
            stop: vec![
                "/usr/bin/velarx".into(),
                "stop".into(),
                "-t".into(),
                "10".into(),
                "web".into(),
            ],
            pid_file: "/run/x/monitor.pid".into(),
            run_root: "/run/velarx".into(),
            bound_to: vec!["pod-p".into()],
            required: Vec::new(),
            opts: &o,
            version: "1.0",
            timestamp: "now",
        };
        let s = u.render();
        for line in [
            "# container-web.service\n# autogenerated by velarx 1.0\n# now\n",
            "RequiresMountsFor=/run/velarx\nBindsTo=pod-p.service\nAfter=pod-p.service\n",
            "\n# User-defined dependencies\nWants=a.service\n",
            "Environment=PODMAN_SYSTEMD_UNIT=%n\nEnvironment=\"FOO=a b\"\nRestart=on-failure\nRestartSec=5\n",
            "TimeoutStopSec=70\nExecStart=/usr/bin/velarx start web\n",
            "ExecStop=/usr/bin/velarx stop \\\n\t-t 10 web\n",
            "PIDFile=/run/x/monitor.pid\nType=forking\n\n[Install]\nWantedBy=default.target\n",
        ] {
            assert!(s.contains(line), "{line:?} in\n{s}");
        }
        let o = Options {
            no_header: true,
            ..Default::default()
        };
        let u = Unit {
            opts: &o,
            bound_to: Vec::new(),
            ..u
        };
        assert!(u
            .render()
            .starts_with("# container-web.service\n\n[Unit]\n"));
    }

    /// The words of a command line as systemd reads them: split on blanks,
    /// quotes group, C escapes everywhere, `$$` and `%%` are `$` and `%`.
    fn systemd_words(line: &str) -> Vec<Vec<u8>> {
        let mut words = Vec::new();
        let mut cur: Option<Vec<u8>> = None;
        let mut quote = None;
        let mut it = line.chars().peekable();
        while let Some(c) = it.next() {
            let w = cur.get_or_insert_with(Vec::new);
            match c {
                c if quote.is_none() && c.is_ascii_whitespace() => {
                    words.extend(cur.take());
                }
                '"' | '\'' if quote == Some(c) => quote = None,
                '"' | '\'' if quote.is_none() => quote = Some(c),
                '$' | '%' if it.peek() == Some(&c) => {
                    it.next();
                    w.push(c as u8);
                }
                '\\' => match it.next().unwrap() {
                    'n' => w.push(b'\n'),
                    't' => w.push(b'\t'),
                    'r' => w.push(b'\r'),
                    'x' => {
                        let hex: String = [it.next().unwrap(), it.next().unwrap()].iter().collect();
                        w.push(u8::from_str_radix(&hex, 16).unwrap());
                    }
                    e => w.extend(e.to_string().bytes()),
                },
                c => w.extend(c.to_string().bytes()),
            }
        }
        assert!(quote.is_none(), "unterminated quote in {line:?}");
        words.extend(cur);
        words
    }

    #[test]
    fn arguments_round_trip_through_systemd_rules() {
        let args = [
            "a",
            "",
            "a b",
            "a\nb",
            "a\tb",
            "say \"hi\"",
            "it's",
            "back\\slash",
            "\\n",
            "$HOME %h",
            "esc\u{1b}[0m",
            "nul\u{7f}",
            "h\u{e9}llo \u{1f600}",
            "\u{85}",
            ";",
            "--opt=a b\nc",
        ];
        let line = args.map(escape_arg).join(" ");
        assert!(!line.contains(['\n', '\u{1b}']), "{line:?}");
        let got = systemd_words(&line);
        let want: Vec<Vec<u8>> = args.iter().map(|a| a.as_bytes().to_vec()).collect();
        assert_eq!(got.len(), want.len(), "{line:?}");
        for (g, w) in got.iter().zip(&want) {
            assert_eq!(String::from_utf8_lossy(g), String::from_utf8_lossy(w));
        }
    }

    /// systemd expands no variable in `Environment=`: a `$$` there stays.
    #[test]
    fn an_environment_value_keeps_its_dollar() {
        assert_eq!(escape_word("A=$B %n"), "\"A=$B %%n\"");
        assert_eq!(escape_word("A=$$"), "A=$$");
    }

    #[test]
    fn arguments_are_escaped_as_podman_does() {
        assert_eq!(escape_arg("a"), "a");
        assert_eq!(escape_arg("a b"), "\"a b\"");
        assert_eq!(escape_arg("a\nb"), "\"a\\nb\"");
        assert_eq!(escape_arg("\u{1b}x"), "\"\\x1bx\"");
        assert_eq!(escape_arg(""), "\"\"");
        assert_eq!(escape_arg("$X%"), "$$X%%");
        assert_eq!(escape_arg("a\\b"), "a\\\\b");
        assert_eq!(service_name("", "-", "x"), "x");
        assert_eq!(service_name("ctr", "_", "x"), "ctr_x");
    }
}
